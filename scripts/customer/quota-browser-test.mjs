import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE_PATH||'playwright')
const base=process.argv[2]||'http://127.0.0.1:4181',artifacts=resolve(process.argv[3]||'/tmp/fellestall-quota-browser')
await mkdir(artifacts,{recursive:true})
const browser=await chromium.launch({headless:true}),ctx=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'})
ctx.setDefaultTimeout(25000);await ctx.route('https://fellestall.no/**',route=>route.abort())
const page=await ctx.newPage(),errors=[];page.on('pageerror',error=>errors.push(error.message))
try {
  const email='kvote-mobil@example.test',password='Et langt kapasitets-passord 123!'
  await page.goto(base+'/#konto/registrer')
  await page.locator('[name=name]').fill('Kapasitetstest');await page.locator('[name=email]').fill(email);await page.locator('[name=password]').fill(password)
  await page.locator('#login-form [type=submit]').click();await page.waitForURL('**/#konto/bekreft')
  const mail=await(await ctx.request.get(base+'/__test/mail?email='+encodeURIComponent(email))).json()
  await page.goto(mail.findLast(row=>row.purpose==='verify').url);await page.waitForURL('**/#konto')
  await page.locator('[name=email]').fill(email);await page.locator('[name=password]').fill(password);await page.locator('#login-form [type=submit]').click()
  await page.waitForURL('**/#sven');await page.locator('#message').waitFor()
  const session=await(await ctx.request.get(base+'/api/customer/session')).json()
  assert.equal(session.account.plan,'free')
  await page.locator('#message').fill('Forklar tallene i kommunen');await page.getByRole('button',{name:'Send melding',exact:true}).click()
  await page.waitForFunction('saved.talks[0]?.messages[0]?.liveAnswer===true')
  await page.evaluate('window.FellestallCustomer.flush()')
  let usage=await(await ctx.request.get(base+'/api/customer/usage')).json();assert(usage.spent>0);assert.equal(usage.held,0)
  const before=usage.spent
  await ctx.request.post(base+'/__test/quota',{data:{freeMonthlyNano:usage.spent+500000}})
  await page.evaluate('window.FellestallCustomer.refreshUsage({force:true})')
  // Modifying browser bookkeeping never credits server capacity.
  await page.evaluate(()=>{saved.svenCapacity={months:{},extraRemaining:999999999999,extraTotal:999999999999};persist()})
  await page.locator('#message').fill('Undersøk neste spørsmål');await page.getByRole('button',{name:'Send melding',exact:true}).click()
  await page.waitForFunction('saved.talks[0].messages[1]?.quotaBlocked===true')
  const pausedId=await page.evaluate('saved.talks[0].messages[1].requestId')
  assert(pausedId)
  usage=await(await ctx.request.get(base+'/api/customer/usage')).json();assert.equal(usage.spent,before);assert.equal(usage.held,0)
  await page.locator('#quota-meter').click();await page.getByText('Gratisversjon',{exact:true}).waitFor()
  assert.equal(await page.locator('#sven-model option[value="claude-opus-5-5"]').evaluate(option=>option.disabled),true)
  await page.screenshot({path:resolve(artifacts,'quota-paused.png')})
  await page.getByRole('button',{name:'Kjøp ekstra kapasitet',exact:true}).click()
  await page.getByText('Ingen kapasitet er lagt til, og ingen betaling er startet.',{exact:true}).waitFor()
  assert.equal((await(await ctx.request.get(base+'/api/customer/usage')).json()).spent,before)
  assert.equal((await(await ctx.request.get(base+'/api/customer/session')).json()).account.plan,'free')
  await page.evaluate('sheet.close()')
  // A trusted fixture operator changes entitlement. This verifies resumption,
  // not Stripe, checkout, tax or a payment webhook.
  const operator=await(await ctx.request.post(base+'/__test/quota',{data:{upgradeUserId:session.user.id}})).json()
  await page.evaluate('window.FellestallCustomer.refreshUsage({force:true})')
  assert.equal(await page.evaluate('window.FellestallCustomer.account.plan'),'paid')
  await page.locator('[data-action="resume-answer:1"]').click()
  await page.waitForFunction('saved.talks[0].messages[1]?.liveAnswer===true')
  await page.evaluate('window.FellestallCustomer.flush()')
  usage=await(await ctx.request.get(base+'/api/customer/usage')).json()
  assert.equal(usage.plan,'paid');assert(usage.spent>0);assert(usage.period.key.startsWith('paid:'));assert.equal(usage.held,0)
  assert.equal(await page.evaluate('Boolean(saved.talks[0].messages[1].quotaBlocked)'),false)
  const jobs=await(await ctx.request.get(base+'/api/customer/resources/jobs')).json()
  assert(jobs.items.some(row=>row.id===pausedId));assert.equal(jobs.items.length,2)
  const after=await(await ctx.request.post(base+'/__test/quota',{data:{}})).json()
  assert.equal(after.modelCalls-operator.modelCalls,1,'Gjenopptak skal starte nøyaktig det manglende modelltrinnet')
  await page.locator('#quota-meter').click();await page.getByText('Betalt versjon',{exact:true}).waitFor()
  assert.equal(await page.locator('#sven-model option[value="claude-opus-5-5"]').evaluate(option=>option.disabled),false)
  await page.screenshot({path:resolve(artifacts,'quota-resumed.png')})
  assert.deepEqual(errors,[])
  console.log('PASS: servermåler, modelltilgang, avvist lokal påfyllsmanipulasjon, kvotepause uten modellkostnad, samme jobb etter intern testoppgradering og ett nytt modelltrinn. Ingen betaling eller Stripe-hendelse er simulert som ferdig produktfunksjon.')
} finally {await ctx.close();await browser.close()}
